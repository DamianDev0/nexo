import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = resolve(ROOT, 'apps/web/src/styles/globals.css')
const TARGET = resolve(ROOT, 'packages/shared-utils/src/brand-palette.generated.ts')

const KEYS = {
  'brand-primary': 'primary',
  'brand-primary-foreground': 'primaryForeground',
  'brand-secondary': 'secondary',
  'brand-accent': 'accent',
  'brand-sidebar': 'sidebar',
  'brand-sidebar-foreground': 'sidebarForeground',
}

function readBrandVars(css) {
  const entries = Object.entries(KEYS).map(([cssVar, key]) => {
    const match = new RegExp(`--${cssVar}:\\s*(#[0-9a-fA-F]{3,8})\\s*;`).exec(css)
    if (!match) throw new Error(`gen-brand-palette: --${cssVar} not found in ${SOURCE}`)
    return [key, match[1].toUpperCase()]
  })
  return Object.fromEntries(entries)
}

const palette = readBrandVars(readFileSync(SOURCE, 'utf8'))

const body = Object.entries(palette)
  .map(([key, hex]) => `  ${key}: '${hex}',`)
  .join('\n')

writeFileSync(
  TARGET,
  `// Generated by scripts/gen-brand-palette.mjs from apps/web/src/styles/globals.css.
// Edit the --brand-* custom properties there, not this file.

export const NEXO_BRAND_PALETTE = {
${body}
} as const
`,
)

process.stdout.write(`[gen-brand-palette] ${TARGET.replace(`${ROOT}/`, '')}\n`)
